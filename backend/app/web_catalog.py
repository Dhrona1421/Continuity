from __future__ import annotations

from dataclasses import asdict, dataclass


@dataclass(frozen=True)
class WebAttackDefinition:
    number: int
    slug: str
    name: str
    family: str
    severity: str
    base_confidence: float
    detection_mode: str
    mitre: tuple[str, ...]
    description: str
    patterns: tuple[str, ...] = ()

    @property
    def rule_id(self) -> str:
        return f"GS-WEB-{self.number:03d}"

    def view(self) -> dict[str, object]:
        result = asdict(self)
        result["rule_id"] = self.rule_id
        result["mitre"] = list(self.mitre)
        result["patterns"] = len(self.patterns)
        return result


