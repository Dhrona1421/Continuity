ATTACK_BY_SLUG = {item.slug: item for item in WEB_ATTACK_CATALOG}
ATTACK_BY_NAME = {item.name.lower(): item for item in WEB_ATTACK_CATALOG}


def resolve_attack_signal(value: str) -> WebAttackDefinition | None:
    normalized = value.strip().lower().replace("-", "_").replace(" ", "_")
    if normalized in ATTACK_BY_SLUG:
        return ATTACK_BY_SLUG[normalized]
    return ATTACK_BY_NAME.get(value.strip().lower())
